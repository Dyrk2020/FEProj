from lnet_tools import RAW

T = bytearray(RAW[0x24bd90:0x24bd90 + 0x40])
# plain-xor byte decodes (bic/and/orr pairs: value = cipher ^ key, key2 = ~key)
for off, key in [(0x18, 0x41), (0x19, 0x9e), (0x1b, 0x84), (0x1c, 0xcd), (0x1e, 0xec),
                 (0x20, 0x7a), (0x29, 0x94), (0x2b, 0xce), (0x2c, 0x24), (0x2d, 0xa5), (0x2e, 0x4b)]:
    T[off] ^= key
# +0x1f: (0x44444444 & ~w)|(0xbbbbbbbb & w) == w ^ 0x44 per bit
T[0x1f] ^= 0x44
# +0x1d: inner = (w & 0x7e) | (~w & 0x81); byte = 0x48 ^ inner
w = T[0x1d]
T[0x1d] = (0x48 ^ ((w & 0x7e) | ((~w) & 0x81))) & 0xFF
# +0x2a: inner2 = (w & 0x1e) | (~w & 0xffffffe1); byte = 0x40 ^ inner2
w = T[0x2a]
T[0x2a] = (0x40 ^ ((w & 0x1e) | ((~w) & 0xffffffe1))) & 0xFF
# vector: bytes 0x00..0x0f = rodata@0x1d85a0 ^ cipher[0:16]
src0 = RAW[0x1d85a0:0x1d85a0 + 16]
for i in range(16):
    T[i] = src0[i] ^ T[i]
# 0x10..0x17 = rodata@0x1d8648 ^ cipher[0x10:0x18]
src1 = RAW[0x1d8648:0x1d8648 + 8]
for i in range(8):
    T[0x10 + i] = src1[i] ^ T[0x10 + i]

print("decoded table @0x24bd90 (0x2f bytes):")
for i in range(0, 0x31, 16):
    print(f"  +{i:02x}: " + " ".join(f"{b:02x}" for b in T[i:i + 16]))
print("ascii:", repr(bytes(T[0:0x2f]).decode('latin-1')))
